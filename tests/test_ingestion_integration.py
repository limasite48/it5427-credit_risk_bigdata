def test_macro_feature_joiner():
    """Verify that MacroFeatureJoiner enriches applications with regional metrics."""
    supp_dir = BASE_DIR / "ingestion-minio-kafka" / "data" / "supplementary"
    joiner = MacroFeatureJoiner(supp_dir)

    # Synthetic applicant with known REGION_POPULATION_RELATIVE
    sample_df = pd.DataFrame(
        {
            "SK_ID_CURR": [100001, 100002],
            "REGION_POPULATION_RELATIVE": [0.018801, 0.003541],
            "AMT_CREDIT": [250000.0, 500000.0],
        }
    )

    enriched = joiner.join_macro_features(sample_df)

    assert "region_code" in enriched.columns
    assert "gdp_growth_yoy_pct" in enriched.columns
    assert "unemployment_rate_pct" in enriched.columns
    assert "cpi_yoy_pct" in enriched.columns
    assert enriched["region_code"].notnull().all()
    assert enriched["gdp_growth_yoy_pct"].notnull().all()


def test_kafka_loan_application_schema_validation():
    """Verify sample loan event satisfies Member 1's JSON Schema."""
    schema_path = (
        BASE_DIR
        / "ingestion-minio-kafka"
        / "schemas"
        / "hc.los.loan-application.v1.schema.json"
    )
    assert schema_path.exists()

    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    validator = Draft202012Validator(schema)

    # Load example event generated by gen_schemas.py
    example_path = (
        BASE_DIR
        / "ingestion-minio-kafka"
        / "schemas"
        / "examples"
        / "hc.los.loan-application.v1.json"
    )
    if example_path.exists():
        example_event = json.loads(example_path.read_text(encoding="utf-8"))
        assert validator.is_valid(example_event)


def test_real_time_credit_scorer():
    """Verify RealTimeCreditScorer processes an incoming event and produces decisions."""
    scorer = RealTimeCreditScorer()

    sample_event = {
        "event_id": "test_event_001",
        "event_type": "loan_application.submitted",
        "customer_id": 999991,
        "payload": {
            "SK_ID_CURR": 999991,
            "AMT_INCOME_TOTAL": 180000.0,
            "AMT_CREDIT": 450000.0,
            "AMT_ANNUITY": 22500.0,
            "DAYS_BIRTH": -12000,
            "DAYS_EMPLOYED": -1500,
            "EXT_SOURCE_1": 0.45,
            "EXT_SOURCE_2": 0.55,
            "EXT_SOURCE_3": 0.60,
            "NAME_INCOME_TYPE": "Working",
            "OCCUPATION_TYPE": "Laborers",
        },
    }

    decision = scorer.process_event(sample_event)

    assert decision["SK_ID_CURR"] == 999991
    assert 0.0 <= decision["default_probability"] <= 1.0
    assert decision["risk_tier"] in ["LOW", "MEDIUM", "HIGH"]
    assert decision["action"] in ["Auto-Approve", "Manual Review", "Decline"]
    assert "top_risk_drivers" in decision
