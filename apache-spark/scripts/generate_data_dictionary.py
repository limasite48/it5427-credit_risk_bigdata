"""Generate docs/DATA_DICTIONARY.md from the ACTUAL Silver/Gold schemas + the documentation in code.

    python -m scripts.generate_data_dictionary
Column meaning comes from (in order): engineered/aggregated feature docs, lineage/flag docs, and the Kaggle
HomeCredit_columns_description.csv (if present in the raw dir).
"""
from __future__ import annotations

from common.config import load_config, path_of
from common.lake import read_table
from common.schemas import SILVER_ORDER, TABLES, silver_name
from common.spark import get_spark
from processing.feature_engineering.features import AGGREGATED, ENGINEERED
from processing.profiling.profile_raw import load_descriptions

GOLD = {
    "integrated_credit_profile": ("1 row per SK_ID_CURR (train + test)", "sk_id_curr",
                                  "application (Silver) + customer_credit_features + engineered features. NO TARGET."),
    "customer_credit_features": ("1 row per SK_ID_CURR", "sk_id_curr", "aggregates of every child source + SYNTHETIC traffic profile"),
    "loan_credit_features": ("1 row per SK_ID_PREV", "sk_id_prev (FK sk_id_curr)", "previous_application + installments/POS/card aggregated per previous loan"),
    "training_labels": ("1 row per SK_ID_CURR in train", "sk_id_curr", "TARGET only - join at training time, never a feature"),
    "data_quality_report": ("1 row per metric per run", "run_at, table, metric", "long-format DQ metrics"),
    "stream_customer_activity_delta": ("1 row per SK_ID_CURR per micro-batch", "sk_id_curr, batch_id", "streaming aggregates (additive)"),
    "stream_customer_snapshot": ("1 row per SK_ID_CURR seen in the stream", "sk_id_curr", "re-aggregation of the deltas"),
    "stream_batch_metrics": ("1 row per micro-batch", "batch_id", "events, latency, customers touched"),
}
SPECIAL = {
    "dataset_split": "train | test (which application file the row comes from)",
    "has_synthetic_profile": "1 if a SYNTHETIC traffic profile exists for the customer",
    "synthetic_data_updated_at": "SYNTHETIC refresh timestamp of the traffic profile",
    "_source_id": "logical source system", "_origin": "ORIGINAL (Kaggle) or SYNTHETIC",
    "_ingest_id": "Bronze snapshot the row comes from", "_ingested_at": "ingestion time of that snapshot",
    "_silver_processed_at": "Silver processing time",
    "_invalid_negative": "flag: a non-negative amount/DPD column is negative",
    "_after_application": "flag: relative date > 0, i.e. after the current application (excluded in Gold)",
    "_dup_business_key": "flag: another row shares the business key (kept)",
    "_orphan_application": "flag: SK_ID_CURR not in application_train/test", "_orphan_bureau": "flag: SK_ID_BUREAU not in bureau",
    "_orphan_previous_application": "flag: SK_ID_PREV not in previous_application",
    "batch_id": "Structured Streaming micro-batch id", "events_total": "events in the micro-batch for the customer",
}


def describe(col: str, desc: dict[str, str]) -> tuple[str, str]:
    if col in ENGINEERED:
        f, m = ENGINEERED[col]
        return f"ENGINEERED: `{f}`", m
    if col in AGGREGATED:
        src, f, m = AGGREGATED[col]
        return f"{src}: `{f}`", m
    if col in SPECIAL:
        return "pipeline", SPECIAL[col]
    if col.endswith("_is_sentinel"):
        return "Silver flag", f"original `{col[:-12].upper()}` was 365243 (not applicable / open-ended); value set to NULL"
    if col.endswith("_outlier"):
        return "Silver flag", f"`{col[:-8]}` at/above the configured outlier quantile (kept)"
    return "Home Credit (original)", desc.get(col, "")


def main() -> str:
    cfg = load_config()
    spark = get_spark("dictionary")
    raw_desc = load_descriptions(path_of(cfg, "raw_dir"))
    desc: dict[str, str] = {}
    for table, cols in raw_desc.items():
        for orig, d in cols.items():
            desc.setdefault(silver_name(orig), d)

    L = ["# Data Dictionary", "",
         "Generated by `python -m scripts.generate_data_dictionary` from the schemas actually written to the lake.", "",
         "Conventions: Silver/Gold column names are the Kaggle names in lower_snake_case. Amounts are in the (unspecified) "
         "currency of the Kaggle data. `DAYS_*` / `MONTHS_*` are relative to the CURRENT application date (negative = before).", "",
         "## 1. Silver tables (cleaned, typed, one per source table)", "",
         "| Table | Logical source | Origin | Grain | Primary key | Foreign keys |", "|---|---|---|---|---|---|"]
    for name in SILVER_ORDER:
        s = TABLES[name]
        fks = "; ".join(f"{','.join(map(silver_name, fk.columns))} → {fk.parent}" for fk in s.foreign_keys) or "—"
        pk = ", ".join(map(silver_name, s.primary_key)) if s.primary_key else "— (event table)"
        L.append(f"| silver/{name} | {s.source_id} | {s.origin} | {s.grain} | {pk} | {fks} |")
    L += ["", "Every Silver table also carries the lineage columns `_source_id, _origin, _ingest_id, _ingested_at, "
          "_silver_processed_at` and the quality flags described in `reports/data_quality/CLEANING_RULES.md`.", ""]

    L += ["## 2. Gold tables", ""]
    for t, (grain, key, what) in GOLD.items():
        try:
            df = read_table(spark, "gold", t, cfg)
        except Exception:  # noqa: BLE001 - table not produced in this run (e.g. streaming not run)
            continue
        L += [f"### gold/{t}", "", f"- Grain: {grain}", f"- Key: `{key}`", f"- Content: {what}", "",
              "| Column | Type | Source / formula | Meaning |", "|---|---|---|---|"]
        for c, typ in df.dtypes:
            src, meaning = describe(c, desc)
            L.append(f"| {c} | {typ} | {src} | {meaning.replace('|', '/')[:160]} |")
        L.append("")
    out = path_of(cfg, "docs_dir") / "DATA_DICTIONARY.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return str(out)


if __name__ == "__main__":
    print(main())
